func TestDetector_DetectHuman(t *testing.T) {
	d := NewDetector()

	commit := &CommitInfo{
		Hash:        "abc123",
		AuthorName:  "John Doe",
		AuthorEmail: "john@example.com",
		Message:     "feat: add new feature",
	}

	result := d.Detect(commit)

	if result.Actor.Kind != cgp.ActorKindHuman {
		t.Errorf("Kind = %s, want %s", result.Actor.Kind, cgp.ActorKindHuman)
	}
	if result.Confidence < 0.9 {
		t.Errorf("Confidence = %f, want >= 0.9", result.Confidence)
	}
	if result.Method != "default_human" {
		t.Errorf("Method = %s, want default_human", result.Method)
	}
}

