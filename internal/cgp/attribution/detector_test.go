func TestDetector_DetectGitHubActions(t *testing.T) {
	d := NewDetector()

	tests := []struct {
		email string
	}{
		{"noreply@github.com"},
		{"actions@github.com"},
		{"github-actions@github.com"},
		{"github-actions[bot]@users.noreply.github.com"},
	}

	for _, tt := range tests {
		commit := &CommitInfo{
			Hash:        "abc123",
			AuthorName:  "GitHub Actions",
			AuthorEmail: tt.email,
			Message:     "chore: automated update",
		}

		result := d.Detect(commit)

		if result.Actor.Kind != cgp.ActorKindCI {
			t.Errorf("For email %s: Kind = %s, want %s", tt.email, result.Actor.Kind, cgp.ActorKindCI)
		}
	}
}

