package attribution

import (
	"regexp"
	"strconv"
	"strings"

	"github.com/relicta-tech/relicta/v4/internal/cgp"
)

// CommitInfo contains commit metadata for attribution detection.
type CommitInfo struct {
	Hash           string
	AuthorName     string
	AuthorEmail    string
	CommitterName  string
	CommitterEmail string
	Message        string
	Trailers       map[string]string
}

// DetectionResult contains the result of attribution detection.
type DetectionResult struct {
	// Actor is the detected actor.
	Actor cgp.Actor

	// Confidence is how confident we are in the detection (0.0-1.0).
	Confidence float64

	// Method describes how the attribution was detected.
	Method string

	// Evidence contains the data that led to this detection.
	Evidence map[string]string
}

// Detector detects which agent or human made changes.
type Detector struct {
	// AgentPatterns maps agent identifiers to their detection patterns.
	agentPatterns map[string]*AgentPattern

	// KnownAgentEmails maps email patterns to agent names.
	knownAgentEmails map[string]string

	// KnownCIEmails maps email patterns to CI system names.
	knownCIEmails map[string]string
}

// AgentPattern defines how to detect a specific agent.
type AgentPattern struct {
	// Name is the agent's display name.
	Name string

	// Model is the AI model name (if applicable).
	Model string

	// EmailPatterns are regex patterns to match author/committer emails.
	EmailPatterns []*regexp.Regexp

	// NamePatterns are regex patterns to match author/committer names.
	NamePatterns []*regexp.Regexp

	// TrailerKeys are git trailer keys that indicate this agent.
	TrailerKeys []string

	// MessagePatterns are regex patterns to match in commit messages.
	MessagePatterns []*regexp.Regexp

	// DefaultTrustLevel is the default trust level for this agent.
	DefaultTrustLevel cgp.TrustLevel
}

// NewDetector creates a new attribution detector with default patterns.
func NewDetector() *Detector {
	d := &Detector{
		agentPatterns:    make(map[string]*AgentPattern),
		knownAgentEmails: make(map[string]string),
		knownCIEmails:    make(map[string]string),
	}
	d.registerDefaultPatterns()
	return d
}

